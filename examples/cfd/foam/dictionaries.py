"""Write OpenFOAM dictionaries from Python values.

Strings are written verbatim, so multi-word entries such as ``bounded Gauss upwind`` stay
as typed. Tuples and lists become ``( ... )``, mappings become sub-dictionaries, ``None``
gives a bare keyword and keys starting with ``#`` are directives without a semicolon.
"""

from collections.abc import Mapping
from pathlib import Path

import numpy as np


def value(item: object) -> str:
    if isinstance(item, (bool, np.bool_)):
        return "true" if item else "false"
    if isinstance(item, str):
        return item
    if isinstance(item, (int, np.integer)):
        return str(int(item))
    if isinstance(item, (float, np.floating)):
        return f"{float(item):.10g}"
    return "(" + " ".join(value(v) for v in item) + ")"


def render(entries: Mapping[str, object], indent: int = 0) -> str:
    pad = " " * indent
    lines = []
    for key, item in entries.items():
        if isinstance(item, Mapping):
            lines.append(f"{pad}{key}\n{pad}{{\n{render(item, indent + 4)}{pad}}}\n")
        elif item is None:
            lines.append(f"{pad}{key};\n")
        elif key.startswith("#"):
            lines.append(f"{pad}{key} {value(item)}\n")
        else:
            lines.append(f"{pad}{key} {value(item)};\n")
    return "".join(lines)


def write_dictionary(
    path: Path, entries: Mapping[str, object], kind: str = "dictionary"
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = {"version": 2.0, "format": "ascii", "class": kind, "object": path.name}
    path.write_text(render({"FoamFile": header}) + "\n" + render(entries))


def write_field(
    path: Path,
    kind: str,
    dimensions: str,
    initial: object,
    boundary: Mapping[str, Mapping[str, object]],
) -> None:
    """A volume field with a uniform initial value."""
    write_dictionary(
        path,
        {
            "dimensions": dimensions,
            "internalField": f"uniform {value(initial)}",
            # every patch generated by snappyHexMesh or the mesh writer must be listed
            "boundaryField": dict(boundary),
        },
        kind,
    )
